/* =========================================================
   VALIDATION
========================================================= */

const currentPasswordSchema =
  z.string()
    .min(
      1,
      "Enter your current password.",
    )
    .max(
      256,
      "Invalid password.",
    );

const updateAccountSchema =
  z.object({
    fullName:
      z.string()
        .trim()
        .max(
          100,
          "Full name must be 100 characters or fewer.",
        ),

    email:
      z.string()
        .trim()
        .toLowerCase()
        .email(
          "Enter a valid email address.",
        )
        .max(
          254,
          "Email address is too long.",
        ),

    currentPassword:
      currentPasswordSchema,
  });

const changePasswordSchema =
  z.object({
    currentPassword:
      currentPasswordSchema,

    newPassword:
      z.string()
        .min(
          12,
          "New password must contain at least 12 characters.",
        )
        .max(
          72,
          "New password must contain 72 characters or fewer.",
        ),

    confirmPassword:
      z.string(),
  })
    .refine(
      (
        values,
      ) =>
        values.newPassword ===
        values.confirmPassword,
      {
        path: [
          "confirmPassword",
        ],

        message:
          "The new passwords do not match.",
      },
    );

const savePolicySchema =
  z.object({
    key:
      z.string()
        .trim()
        .min(
          1,
          "Policy key is required.",
        ),

    value:
      z.string(),
  });

const revokeSessionsSchema =
  z.object({
    currentPassword:
      currentPasswordSchema,
  });

